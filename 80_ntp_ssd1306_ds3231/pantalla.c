#include <stdio.h>
#include <string.h>
#include "pico/stdlib.h"
#include "ssd1306_i2c.h"

#include "pantalla.h"

#define LOGO_UTN_WIDTH      (128)
#define LOGO_UTN_HEIGHT     (32)
#define LOGO_UTN_CAB_WIDTH  (32)
#define LOGO_UTN_CAB_HEIGHT (32)

extern const unsigned char logo_inspt[];
extern const unsigned char logo_inspt_cab[];

//Para gráficos
render_area_t ssd1306_frame_area = {
    start_col: 0,
    end_col : SSD1306_WIDTH - 1,
    start_page : 0,
    end_page : SSD1306_NUM_PAGES - 1
};
//Para texto
uint8_t ssd1306_text_buffer[SSD1306_BUF_LEN];

void LimpiaDisplay(void) {
    SSD1306_calc_render_area_buflen(&ssd1306_frame_area);
    memset(ssd1306_text_buffer, 0, SSD1306_BUF_LEN);
    SSD1306_render(ssd1306_text_buffer, &ssd1306_frame_area);
}

void DibujaLogoGrande(void) {
    ssd1306_frame_area.start_page = 0;
    ssd1306_frame_area.start_col = 0;
    ssd1306_frame_area.end_page = ((LOGO_UTN_HEIGHT / SSD1306_PAGE_HEIGHT) - 1);
    ssd1306_frame_area.end_col = (LOGO_UTN_WIDTH - 1);

    SSD1306_calc_render_area_buflen(&ssd1306_frame_area);
    SSD1306_render((uint8_t*)(logo_inspt), &ssd1306_frame_area);
}

void DibujaLogoChico(void) {
    ssd1306_frame_area.start_page = 0;
    ssd1306_frame_area.start_col = 0;
    ssd1306_frame_area.end_page = ((LOGO_UTN_CAB_HEIGHT / SSD1306_PAGE_HEIGHT) - 1);
    ssd1306_frame_area.end_col = (LOGO_UTN_CAB_WIDTH - 1);

    SSD1306_calc_render_area_buflen(&ssd1306_frame_area);
    SSD1306_render((uint8_t*)(logo_inspt_cab), &ssd1306_frame_area);
}

void EscribeRenglon(uint8_t* texto, uint8_t nro_renglon, uint8_t margen) {
    int y = 0;

    memset(ssd1306_text_buffer, 0, SSD1306_BUF_LEN);

    for (int i = 0; i < count_of(texto); i++) {
        SSD1306_write_string(ssd1306_text_buffer, 0, y, &(texto[i]));
        y += 8;
    }

    ssd1306_frame_area.start_page = nro_renglon;
    ssd1306_frame_area.start_col = margen;
    ssd1306_frame_area.end_page = (nro_renglon + 1);
    ssd1306_frame_area.end_col = (SSD1306_WIDTH - 1);

    SSD1306_render(ssd1306_text_buffer, &ssd1306_frame_area);
}

